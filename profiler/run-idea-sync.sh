#!/usr/bin/env bash
# gradle-profiler IDE sync benchmark for the work-based sync prototype.
#
#   run-idea-sync.sh <idea install dir or .app> <project dir> <sandbox dir> <output dir> stock|wbs [gradle-profiler options...]
#
# Scenarios (all in one file, generated into <output dir>/idea-sync.scenarios):
#   sync_hit            plain re-sync: the configuration cache entry is kept (a hit for the task sync; stock misses anyway)
#   sync_miss_settings  the settings script's content is changed before every sync (forced miss, the common edit case)
#   sync_miss_cleared   .gradle/configuration-cache is deleted before every sync (miss without a script change)
#
# How the profiler sandboxes the IDE (gradle-profiler 0.26, org.gradle.profiler.ide.*): it starts the IDE through its
# launcher (Contents/MacOS/idea, bin/idea.sh) with IDEA_VM_OPTIONS pointing at a generated vmoptions file that holds
# -Didea.config.path/-Didea.system.path/-Didea.plugins.path/-Didea.log.path for <sandbox dir>/{config,system,plugins,logs},
# its -javaagent, and the scenario's ide-jvm-args. Consequences for the kit:
#   - the IDE's own bin/idea.vmoptions (where the kit put the -Dwbs.* options) is NOT read: the options go into
#     ide-jvm-args here, taken from the kit's wbs.vmoptions (without the paths selector, the sandbox replaces it);
#   - the plugin must be in <sandbox dir>/plugins: the profiler only adds and removes its own gradle-profiler-ide-plugin
#     there and leaves other plugin directories alone, so it is copied in before the run;
#   - the patched platform classes live in the WBS app's jars, so pass the WBS app as the install dir for "wbs".
# Without a display the profiler runs the IDE with its headless-starter.
set -euo pipefail
IDEA=$1; PROJECT=$2; SANDBOX=$3; OUT=$4; MODE=$5; shift 5
HERE=$(cd "$(dirname "$0")" && pwd)
KIT=${WBS_KIT:-$HERE/../dist-unpacked}   # a directory holding plugin/wbs-task-transport and wbs.vmoptions (the unpacked kit)
PROFILER=${GRADLE_PROFILER:-gradle-profiler}
mkdir -p "$OUT" "$SANDBOX/plugins"
JVM_ARGS='"-Xms256m", "-Xmx4096m"'
if [[ $MODE == wbs ]]; then
  [[ -d "$KIT/plugin/wbs-task-transport" ]] || { echo "no kit at $KIT (set WBS_KIT to the unpacked kit directory)" >&2; exit 1; }
  rm -rf "$SANDBOX/plugins/wbs-task-transport"; cp -R "$KIT/plugin/wbs-task-transport" "$SANDBOX/plugins/"
  while IFS= read -r line; do
    [[ $line == -Dwbs.* ]] || continue
    JVM_ARGS+=", \"$line\""
  done < "$KIT/wbs.vmoptions"
  echo "plugin installed into $SANDBOX/plugins, $(grep -c '^-Dwbs' "$KIT/wbs.vmoptions") wbs options added"
elif [[ $MODE != stock ]]; then
  echo "mode must be stock or wbs" >&2; exit 1
fi
SETTINGS=settings.gradle.kts; [[ -f "$PROJECT/$SETTINGS" ]] || SETTINGS=settings.gradle
cat > "$OUT/idea-sync.scenarios" <<SCN
# generated by run-idea-sync.sh for mode $MODE
sync_hit {
  title = "IDE sync, configuration cache kept ($MODE)"
  idea-sync { ide-jvm-args = [$JVM_ARGS] }
  warm-ups = 1
  iterations = 3
}
sync_miss_settings {
  title = "IDE sync, settings script changed before every sync ($MODE)"
  idea-sync { ide-jvm-args = [$JVM_ARGS] }
  apply-build-script-change-to = "$SETTINGS"
  warm-ups = 1
  iterations = 3
}
sync_miss_cleared {
  title = "IDE sync, configuration cache deleted before every sync ($MODE)"
  idea-sync { ide-jvm-args = [$JVM_ARGS] }
  clear-configuration-cache-state-before = BUILD
  warm-ups = 1
  iterations = 3
}
SCN
echo "scenarios: $OUT/idea-sync.scenarios"
exec "$PROFILER" --benchmark --scenario-file "$OUT/idea-sync.scenarios" --project-dir "$PROJECT" \
  --idea-install-dir "$IDEA" --idea-sandbox-dir "$SANDBOX" --output-dir "$OUT" "$@"
