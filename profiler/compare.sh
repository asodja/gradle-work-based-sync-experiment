#!/usr/bin/env bash
# One command: stock IDE vs WBS kit with gradle-profiler, same scenarios, one merged report.
#
#   profiler/compare.sh <stock IDEA app> <WBS IDEA app> <project dir> [output dir]
#
# Environment (optional): SCENARIOS="sync_miss_settings sync_hit sync_miss_cleared" (default: the two first),
# WARMUPS=1, ITERATIONS=3, WBS_KIT=<unpacked kit dir> (default: the kit next to this repo), GRADLE_PROFILER=<binary>.
# Needs gradle-profiler 0.26+ on the PATH (or GRADLE_PROFILER) and python3 for the merged table.
set -euo pipefail
STOCK=$1; WBS=$2; PROJECT=$3; OUT=${4:-$HOME/wbs-profiler-$(date +%Y%m%d-%H%M)}
HERE=$(cd "$(dirname "$0")" && pwd)
SCENARIOS=${SCENARIOS:-sync_miss_settings sync_hit}; WARMUPS=${WARMUPS:-1}; ITERATIONS=${ITERATIONS:-3}
[[ $WARMUPS -ge 1 ]] || WARMUPS=1   # gradle-profiler refuses zero warm-ups for a benchmark
PROFILER=${GRADLE_PROFILER:-gradle-profiler}
# the same Gradle user home for both IDEs: without the option the profiler uses a fresh ./gradle-user-home for the
# stock sync (its agent injects it) while the kit's own Gradle invocations use the default one
GUH=${GRADLE_USER_HOME:-$HOME/.gradle}
KIT=${WBS_KIT:-}
if [[ -z $KIT ]]; then
  for c in "$HERE/../wbs-ide-kit-262.10315.125" "$HERE/../dist/wbs-ide-kit-262.10315.125"; do [[ -d $c ]] && KIT=$c && break; done
  if [[ -z $KIT && -f "$HERE/../dist/wbs-ide-kit-262.10315.125.tar.gz" ]]; then
    KIT=$(mktemp -d)/kit; mkdir -p "$KIT"; tar xzf "$HERE/../dist/wbs-ide-kit-262.10315.125.tar.gz" -C "$KIT" --strip-components 1
  fi
fi
[[ -n $KIT && -f "$KIT/wbs.vmoptions" ]] || { echo "kit not found; set WBS_KIT to the unpacked kit directory" >&2; exit 1; }
command -v "$PROFILER" >/dev/null || { echo "gradle-profiler not found; set GRADLE_PROFILER" >&2; exit 1; }
for app in "$STOCK" "$WBS"; do [[ -d $app ]] || { echo "no IDE at $app" >&2; exit 1; }; done
mkdir -p "$OUT"
SETTINGS=settings.gradle.kts; [[ -f "$PROJECT/$SETTINGS" ]] || SETTINGS=settings.gradle

scenario_file() { # scenario_file <mode> <file>
  local mode=$1 file=$2 args='"-Xms256m", "-Xmx4096m"'
  if [[ $mode == wbs ]]; then while IFS= read -r l; do [[ $l == -Dwbs.* ]] && args+=", \"$l\""; done < "$KIT/wbs.vmoptions"; fi
  {
    echo "# generated by compare.sh, mode $mode"
    for s in $SCENARIOS; do
      case $s in
        sync_hit) extra=""; title="cache kept";;
        sync_miss_settings) extra="  apply-build-script-change-to = \"$SETTINGS\""; title="settings script changed before every sync";;
        sync_miss_cleared) extra="  clear-configuration-cache-state-before = BUILD"; title="configuration cache deleted before every sync";;
        *) echo "unknown scenario $s" >&2; exit 1;;
      esac
      printf '%s {\n  title = "%s"\n  idea-sync { ide-jvm-args = [%s] }\n%s\n  warm-ups = %s\n  iterations = %s\n}\n' "$s" "$s ($mode): $title" "$args" "$extra" "$WARMUPS" "$ITERATIONS"
    done
  } > "$file"
}

run() { # run <mode> <app>
  local mode=$1 app=$2
  local sandbox="$OUT/sandbox-$mode" result="$OUT/$mode"
  mkdir -p "$sandbox/plugins" "$result"
  if [[ $mode == wbs ]]; then rm -rf "$sandbox/plugins/wbs-task-transport"; cp -R "$KIT/plugin/wbs-task-transport" "$sandbox/plugins/"; fi
  scenario_file "$mode" "$result/idea-sync.scenarios"
  echo "== $mode: $app  ($SCENARIOS; $WARMUPS warm-up(s), $ITERATIONS iterations)"
  "$PROFILER" --benchmark --scenario-file "$result/idea-sync.scenarios" --project-dir "$PROJECT" \
    --gradle-user-home "$GUH" --idea-install-dir "$app" --idea-sandbox-dir "$sandbox" --output-dir "$result" 2>&1 | tee "$result/profiler.log" | grep -E "Running scenario|Full sync|FAILED|rror" || true
  (cd "$PROJECT" && git checkout -- "$SETTINGS" 2>/dev/null) || true
}
run stock "$STOCK"
run wbs "$WBS"

python3 "$HERE/merge-report.py" "$OUT" | tee "$OUT/report.md"
echo "report: $OUT/report.md"
